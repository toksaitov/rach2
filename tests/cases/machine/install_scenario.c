/*
 * install_scenario.c: the scenario of machine.install.loop
 * (tests/cases/machine.install.json). The machine builds and installs its
 * own kernel on a GRUB disk, and the trial, the commit, the fallback and the
 * repair are checked on the booted disk; then the environment blocks of the
 * interruption matrix, which the scenario writes into the disk's copy, boot
 * the slot each selects.
 *
 * SeaBIOS boots the disk with no -kernel, so what runs is what GRUB reads
 * from the boot partition, and a boot after an install runs the installed
 * kernel. Each pass edits a marker of its own into the kernel's banner in
 * /src/rach2, so the banner says which kernel runs; the slot on the command
 * line says only which entry GRUB took. The second pass starts from the disk
 * the first changed, which shows that the loop can be repeated. QEMU runs
 * with -no-reboot, so `reboot -f` ends a boot with a reset and `poweroff -f`
 * with a shutdown, and the next boot of the machine is a QEMU of its own on
 * the same copy of the disk, which keeps what the boots before it wrote.
 */
#include <fcntl.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#include "netcase.h"

/* The case's one machine and its disk. */
#define MACHINE "install"
#define DISK    "install-disk"

/* What the console says when the boot is ready for a login. */
#define LOGIN "rach2 login:"

/* The environment block of GRUB: 1024 bytes, which begin with this header in
 * a file of the boot partition, so at the start of a sector of the disk. */
#define ENV_HEADER "# GRUB Environment Block"
#define ENV_BYTES  1024
#define SECTOR     512

/* The first two lines of a complete block, as grub-editenv writes them. */
#define ENV_TOP \
    ENV_HEADER "\n# WARNING: Do not edit this file by tools other than grub-editenv!!!\n"

/* The marker the second pass installs, by which the matrix's boots tell the
 * candidate from the fallback before any login. */
#define LAST_TOKEN "IKMB"

/* One pass of the install loop. */
struct pass {
    unsigned n;
    const char *old;   /* the banner's text that the pass replaces */
    const char *mark;  /* the text that replaces it */
    const char *token; /* the part of it the pass's kernel alone prints */
};

static const struct pass passes[] = {
    {1, "Rach2 Booting", "Rach2 Bt IKMA", "IKMA"},
    {2, "IKMA", "IKMB", LAST_TOKEN},
};

/* What the steps share. */
struct install {
    struct net_case u;
    struct net_boot b;
    unsigned boots;    /* the machine's boots so far */
    unsigned commands; /* the commands typed so far, which number their ends */
    char password[128];
    const char *copy; /* the private copy of the disk */
    long env;         /* the environment block's offset in the disk, or -1 */
    uint64_t login;   /* the offset just past this boot's login prompt */
};

/** Give the name of end `e`, to show in a failure. */
static const char *end_name(enum etude_end e)
{
    static const char *const names[] = {"exited",      "signaled",     "init_exited", "init_killed",
                                        "panic",       "reset",        "shutdown",    "halted",
                                        "qemu_exited", "accel_failed", "stopped",     "lost"};

    return (unsigned)e < sizeof(names) / sizeof(names[0]) ? names[e] : "unknown";
}

/**
 * Report assertion `id` as net_assert does, and when it failed, end the
 * attempt's work there, since the steps after it depend on what it checks:
 * every later assertion is reported not run.
 */
static void need(struct install *s, const char *id, int held, const char *format, ...)
{
    char detail[160];
    va_list ap;

    va_start(ap, format);
    vsnprintf(detail, sizeof(detail), format, ap);
    va_end(ap);
    net_assert(&s->u, id, held, "%s", detail);
    if (!held && net_ok(&s->u)) {
        net_fail(&s->u, "%s failed", id);
        s->u.told = 1;
    }
}

/** Give in `buf` the identity of pass `p`'s assertion or step `name`. */
static const char *pass_id(const struct pass *p, const char *name, char *buf, size_t size)
{
    snprintf(buf, size, "p%u-%s", p->n, name);
    return buf;
}

/**
 * Find the environment block in the disk's artifact: the offset of the first
 * sector that begins with its header, or -1.
 */
static long find_env(const char *path)
{
    FILE *f = path != NULL ? fopen(path, "rb") : NULL;
    char sector[SECTOR];
    long at = -1, off = 0;

    while (f != NULL && fread(sector, 1, sizeof(sector), f) == sizeof(sector)) {
        if (memcmp(sector, ENV_HEADER, strlen(ENV_HEADER)) == 0) {
            at = off;
            break;
        }
        off += SECTOR;
    }
    if (f != NULL)
        fclose(f);
    return at;
}

/** Write `block`, ENV_BYTES bytes, over the environment block of the
 * disk's copy, with the machine stopped. */
static void write_env(struct install *s, const unsigned char *block)
{
    int fd;

    if (!net_ok(&s->u))
        return;
    fd = open(s->copy, O_WRONLY);
    if (fd < 0 || pwrite(fd, block, ENV_BYTES, (off_t)s->env) != ENV_BYTES)
        net_fail(&s->u, "the environment block of the copy could not be written");
    if (fd >= 0 && close(fd) != 0)
        net_fail(&s->u, "the copy of the disk could not be closed");
}

/** Make `block` a complete environment block of `lines` after the header,
 * filled with `#` to its length, as grub-editenv writes one. */
static void craft_env(unsigned char block[ENV_BYTES], const char *lines)
{
    size_t top = strlen(ENV_TOP), n = strlen(lines);

    memset(block, '#', ENV_BYTES);
    memcpy(block, ENV_TOP, top);
    memcpy(block + top, lines, n);
}

/** Boot the machine again on the copy of the disk, and wait for its login
 * prompt, keeping the offset past it. */
static void boot(struct install *s)
{
    s->boots++;
    s->login = 0;
    net_boot(&s->b, &s->u, MACHINE, s->boots, NULL);
    net_times(&s->b, LOGIN, 1, &s->login);
}

/** Log in at the console as root. */
static void login(struct install *s)
{
    net_login(&s->b, "root", s->password, "# ");
}

/** End the machine with QMP's `quit`, as a power cut would, and wait for it. */
static void quit(struct install *s)
{
    struct etude_termination end;
    char *reply = NULL;

    if (!net_ok(&s->u))
        return;
    etude_qmp(s->b.m, "quit", NULL, &reply);
    free(reply);
    etude_wait_end(s->b.m, &end);
}

/** Type `command`, which ends the boot, and require that it end `want`. */
static void end_with(struct install *s, const char *command, enum etude_end want)
{
    struct etude_termination end;
    enum etude_status st;

    if (net_line(&s->b, command) != ETUDE_OK)
        return;
    end.end = ETUDE_END_LOST;
    st = etude_wait_end(s->b.m, &end);
    if (st != ETUDE_OK || end.end != want)
        net_fail(&s->u, "%s ended the boot %s, not %s", command, end_name(end.end), end_name(want));
}

/**
 * Type `command` at root's shell, with an echo of a numbered end after it,
 * and give what the console shows from the typed line to that end, from
 * malloc, or NULL after a failed operation.
 */
static char *run(struct install *s, const char *command)
{
    char line[512], marker[32];
    char *text = NULL;

    s->commands++;
    snprintf(line, sizeof(line), "%s; echo END\"\"%u.", command, s->commands);
    snprintf(marker, sizeof(marker), "END%u.", s->commands);
    net_command(&s->b, line, marker, &text);
    return text;
}

/** Read the boot's slot from /proc/cmdline and report assertion `id`: it
 * must be `want`, such as `rach2.slot=candidate`. */
static void slot(struct install *s, const char *id, const char *want)
{
    char *text = run(s, "busybox grep -o 'rach2.slot=[a-z]*' /proc/cmdline");

    net_assert(&s->u, id, text != NULL && strstr(text, want) != NULL,
               "/proc/cmdline does not have %s", want);
    free(text);
}

/** Report assertion `id`: the console of this boot has `token` before its
 * login prompt, where the kernel's banner is. */
static void marked(struct install *s, const char *id, const char *token)
{
    uint64_t at = 0;
    enum etude_status st = net_ok(&s->u) ? etude_console_find(s->b.m, token, 0, &at) : ETUDE_FAILED;

    net_assert(&s->u, id, st == ETUDE_OK && at <= s->login,
               st == ETUDE_OK ? "%s comes after the login prompt" : "the boot never prints %s",
               token);
}

/** Commit the running candidate and report assertion `id`: bootctl says so
 * and exits 0. */
static void commit(struct install *s, const char *id)
{
    char *text = run(s, "bootctl commit; echo COMMIT-STATUS $?");

    net_assert(&s->u, id,
               text != NULL && strstr(text, "bootctl: committed") != NULL &&
                   net_number_after(text, "COMMIT-STATUS ") == 0,
               "bootctl commit exited %ld", net_number_after(text, "COMMIT-STATUS "));
    free(text);
}

/** Step `pN-build`: edit the pass's marker into the banner, build the
 * kernel on the machine, install it as a trial and reboot into it. */
static void build(struct install *s, const struct pass *p)
{
    char id[32], command[400], *text;
    long n;

    net_step(&s->u, pass_id(p, "build", id, sizeof(id)));
    boot(s);
    login(s);
    slot(s, pass_id(p, "candidate", id, sizeof(id)), "rach2.slot=candidate");
    snprintf(command, sizeof(command),
             "cd /src/rach2 && busybox sed -i 's/%s/%s/' sys/arch/x86/boot.c && "
             "busybox grep -c '%s' sys/arch/x86/boot.c | busybox sed s/^/MARKS=/",
             p->old, p->mark, p->mark);
    text = run(s, command);
    n = net_number_after(text, "MARKS=");
    need(s, pass_id(p, "edited", id, sizeof(id)), n == 1, "boot.c has %ld lines with %s", n,
         p->mark);
    free(text);
    text = run(s, "make -f guest.mk > /tmp/ik.out 2>&1; s=$?; "
                  "[ $s -eq 0 ] || busybox tail -n 5 /tmp/ik.out; echo BUILD-STATUS $s");
    n = net_number_after(text, "BUILD-STATUS ");
    need(s, pass_id(p, "built", id, sizeof(id)), n == 0, "make -f guest.mk exited %ld", n);
    free(text);
    text = run(s, "bootctl kernel kernel; echo INSTALL-STATUS $?");
    n = net_number_after(text, "INSTALL-STATUS ");
    need(s, pass_id(p, "installed", id, sizeof(id)), n == 0, "bootctl kernel exited %ld", n);
    free(text);
    text = run(s, "bootctl commit; echo COMMIT-STATUS $?");
    n = net_number_after(text, "COMMIT-STATUS ");
    net_assert(&s->u, pass_id(p, "armed", id, sizeof(id)), n == 1,
               "bootctl commit exited %ld with the trial armed", n);
    free(text);
    end_with(s, "reboot -f", ETUDE_END_RESET);
}

/** Step `pN-trial`: the trial boot runs the kernel built, and is committed. */
static void trial(struct install *s, const struct pass *p)
{
    char id[32];

    net_step(&s->u, pass_id(p, "trial", id, sizeof(id)));
    boot(s);
    marked(s, pass_id(p, "trial-marker", id, sizeof(id)), p->token);
    login(s);
    slot(s, pass_id(p, "trial-candidate", id, sizeof(id)), "rach2.slot=candidate");
    commit(s, pass_id(p, "trial-commit", id, sizeof(id)));
    end_with(s, "poweroff -f", ETUDE_END_SHUTDOWN);
}

/** Step `pN-cold`: a cold boot runs the committed kernel, whose first sector
 * is then destroyed at the extent bootctl names. */
static void cold(struct install *s, const struct pass *p)
{
    char id[32], *text;
    long sector, n;

    net_step(&s->u, pass_id(p, "cold", id, sizeof(id)));
    boot(s);
    marked(s, pass_id(p, "cold-marker", id, sizeof(id)), p->token);
    login(s);
    slot(s, pass_id(p, "cold-candidate", id, sizeof(id)), "rach2.slot=candidate");
    text = run(s, "S=$(bootctl status | "
                  "busybox awk '/^bootctl: candidate: first sector/{print $5}' | "
                  "busybox tr -d ,); echo SECTOR=$S; "
                  "busybox dd if=/dev/zero of=/dev/bootpart bs=512 seek=$S count=1 2>/dev/null; "
                  "echo CORRUPT-STATUS $?");
    sector = net_number_after(text, "SECTOR=");
    n = net_number_after(text, "CORRUPT-STATUS ");
    need(s, pass_id(p, "corrupt", id, sizeof(id)), sector >= 0 && n == 0,
         "the candidate's first sector, %ld, was not written: dd exited %ld", sector, n);
    free(text);
    end_with(s, "reboot -f", ETUDE_END_RESET);
}

/** Step `pN-fallback`: GRUB takes the fallback, which runs the older kernel
 * and installs the built one again. */
static void fallback(struct install *s, const struct pass *p)
{
    char id[32], *text;
    long n;

    net_step(&s->u, pass_id(p, "fallback", id, sizeof(id)));
    boot(s);
    login(s);
    slot(s, pass_id(p, "fallback", id, sizeof(id)), "rach2.slot=fallback");
    text = net_ok(&s->u) ? net_text(&s->b, 0, s->b.at) : NULL;
    net_assert(&s->u, pass_id(p, "fallback-unmarked", id, sizeof(id)),
               text != NULL && strstr(text, p->token) == NULL, "the fallback boot prints %s",
               p->token);
    free(text);
    text = run(s, "cd /src/rach2 && bootctl kernel kernel; echo REPAIR-STATUS $?");
    n = net_number_after(text, "REPAIR-STATUS ");
    need(s, pass_id(p, "repair", id, sizeof(id)), n == 0, "bootctl kernel exited %ld", n);
    free(text);
    end_with(s, "reboot -f", ETUDE_END_RESET);
}

/** Step `pN-repaired`: the repaired candidate runs the kernel built, and is
 * committed. */
static void repaired(struct install *s, const struct pass *p)
{
    char id[32];

    net_step(&s->u, pass_id(p, "repaired", id, sizeof(id)));
    boot(s);
    marked(s, pass_id(p, "repaired-marker", id, sizeof(id)), p->token);
    login(s);
    slot(s, pass_id(p, "repaired-candidate", id, sizeof(id)), "rach2.slot=candidate");
    commit(s, pass_id(p, "repair-commit", id, sizeof(id)));
    end_with(s, "poweroff -f", ETUDE_END_SHUTDOWN);
}

/**
 * A step of the matrix: write `block` over the copy's environment block,
 * boot to the login prompt with nothing typed, end the machine, and report
 * assertion `id`: the last pass's marker before the prompt when `candidate`
 * is nonzero, and nowhere on the console otherwise.
 */
static void matrix(struct install *s, const char *step, const char *id,
                   const unsigned char block[ENV_BYTES], int candidate)
{
    enum etude_status st = ETUDE_FAILED;
    uint64_t at = 0;

    net_step(&s->u, step);
    write_env(s, block);
    boot(s);
    quit(s);
    if (net_ok(&s->u))
        st = etude_console_find(s->b.m, LAST_TOKEN, 0, &at);
    if (candidate)
        net_assert(&s->u, id, st == ETUDE_OK && at <= s->login,
                   "the candidate's %s is not before the login prompt", LAST_TOKEN);
    else
        net_assert(&s->u, id, st == ETUDE_FAILED, "the boot %s %s",
                   st == ETUDE_OK ? "prints" : "cannot be shown not to print", LAST_TOKEN);
}

int etude_scenario(struct etude_case *c)
{
    unsigned char block[ENV_BYTES];
    struct install s;
    size_t i;

    memset(&s, 0, sizeof(s));
    net_case(&s.u, c);
    net_secret(&s.u, "demo-password", s.password, sizeof(s.password));
    if (net_ok(&s.u) && (s.copy = etude_private_copy(c, DISK)) == NULL)
        net_fail(&s.u, "the disk has no private copy");
    s.env = find_env(etude_artifact(c, DISK));
    need(&s, "env-block", s.env >= 0, "no sector of the disk begins with %s", ENV_HEADER);
    for (i = 0; i < sizeof(passes) / sizeof(passes[0]); i++) {
        build(&s, &passes[i]);
        trial(&s, &passes[i]);
        cold(&s, &passes[i]);
        fallback(&s, &passes[i]);
        repaired(&s, &passes[i]);
    }
    memset(block, 0xde, SECTOR);
    memset(block + SECTOR, 0xad, ENV_BYTES - SECTOR);
    matrix(&s, "matrix-header", "header-fallback", block, 0);
    craft_env(block, "saved_entry=fallback\n");
    matrix(&s, "matrix-old", "old-fallback", block, 0);
    craft_env(block, "saved_entry=fallback\nnext_entry=candidate\n");
    matrix(&s, "matrix-new", "new-candidate", block, 1);
    return net_end(&s.u);
}
