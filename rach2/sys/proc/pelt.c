/*
 * pelt.c: per-entity load tracking, as Linux 6.12's kernel/sched/pelt.c and
 * the load averages of fair.c keep it, for the fair class's balancing.
 */
#include "pelt.h"
#include "../timer.h"

/* A thread's entity owns no queue; a group's owns its group's queue. */
#define entity_is_task(se) ((se)->my_q == NULL)

/** The weight PELT multiplies by (se_weight). Weights are unscaled
 * (fair.h), so this is the weight itself. */
static unsigned long se_weight(const struct sched_entity *se)
{
    return se->load.weight;
}

/** Whether an entity counts as runnable, and how many threads below a group
 * entity do (se_runnable). */
static unsigned long se_runnable(const struct sched_entity *se)
{
    return entity_is_task(se) ? (se->on_rq != 0) : se->runnable_weight;
}

/** The group entity that owns `cfs_rq` on its processor, NULL for a root
 * queue. */
static struct sched_entity *cfs_rq_group_se(const struct cfs_rq *cfs_rq)
{
    return cfs_rq->tg->se ? cfs_rq->tg->se[cfs_rq->cpu] : NULL;
}

/* y^n for n below LOAD_AVG_PERIOD, scaled by 2^32, with y^32 = 1/2
 * (sched-pelt.h, generated by Documentation/scheduler/sched-pelt). */
static const uint32_t runnable_avg_yN_inv[LOAD_AVG_PERIOD] = {
    0xffffffff, 0xfa83b2da, 0xf5257d14, 0xefe4b99a, 0xeac0c6e6, 0xe5b906e6, 0xe0ccdeeb, 0xdbfbb796,
    0xd744fcc9, 0xd2a81d91, 0xce248c14, 0xc9b9bd85, 0xc5672a10, 0xc12c4cc9, 0xbd08a39e, 0xb8fbaf46,
    0xb504f333, 0xb123f581, 0xad583ee9, 0xa9a15ab4, 0xa5fed6a9, 0xa2704302, 0x9ef5325f, 0x9b8d39b9,
    0x9837f050, 0x94f4efa8, 0x91c3d373, 0x8ea4398a, 0x8b95c1e3, 0x88980e80, 0x85aac367, 0x82cd8698,
};

/* Each processor's real-time and interrupt averages (rq->avg_rt, avg_irq),
 * under sched_lock. */
static struct sched_avg pelt_rt[NR_CPUS];
static struct sched_avg pelt_irq[NR_CPUS];

/** `a` times `b`, shifted right by 32, in 64 bits without a 128-bit product:
 * Linux's mul_u64_u32_shr for a shift of 32. */
static uint64_t pelt_mul_shr32(uint64_t a, uint32_t b)
{
    uint64_t hi = (a >> 32) * b, lo = (a & 0xffffffffu) * b;

    return hi + (lo >> 32);
}

/** `n` divided by `d`, both 64 bits wide, with no libgcc helper. */
static uint64_t pelt_div(uint64_t n, uint64_t d)
{
    if ((d >> 32) == 0) {
        return tick_div(n, (uint32_t)d, NULL);
    }
    return tick_div64(n, d, NULL);
}

/** Subtract `v` from `*p`, stopping at 0 (sub_positive). */
static void pelt_sub_ul(unsigned long *p, unsigned long v)
{
    *p = *p > v ? *p - v : 0;
}

/** As `pelt_sub_ul`, for a 64-bit sum. */
static void pelt_sub_u64(uint64_t *p, uint64_t v)
{
    *p = *p > v ? *p - v : 0;
}

/** As `pelt_sub_ul`, for a 32-bit sum. */
static void pelt_sub_u32(uint32_t *p, uint32_t v)
{
    *p = *p > v ? *p - v : 0;
}

/** Add a signed `v` to `*p`, stopping at 0 (add_positive). */
static void pelt_add_ul(unsigned long *p, long v)
{
    if (v < 0) {
        pelt_sub_ul(p, (unsigned long)-v);
    } else {
        *p += (unsigned long)v;
    }
}

/** As `pelt_add_ul`, for a 64-bit sum. */
static void pelt_add_u64(uint64_t *p, int64_t v)
{
    if (v < 0) {
        pelt_sub_u64(p, (uint64_t)-v);
    } else {
        *p += (uint64_t)v;
    }
}

/** As `pelt_add_ul`, for a 32-bit sum. */
static void pelt_add_u32(uint32_t *p, long v)
{
    if (v < 0) {
        pelt_sub_u32(p, (uint32_t)-v);
    } else {
        *p += (uint32_t)v;
    }
}

uint64_t pelt_decay_load(uint64_t val, uint64_t n)
{
    unsigned int local_n;

    if (n > LOAD_AVG_PERIOD * 63) {
        return 0;
    }
    local_n = (unsigned int)n;
    if (local_n >= LOAD_AVG_PERIOD) {
        val >>= local_n / LOAD_AVG_PERIOD;
        local_n %= LOAD_AVG_PERIOD;
    }
    return pelt_mul_shr32(val, runnable_avg_yN_inv[local_n]);
}

/**
 * The contribution of `periods` whole periods passed, the remainder `d1` of
 * the period the last update was in and the part `d3` of the current one:
 * d1 y^p + 1024 (y + ... + y^(p-1)) + d3 (__accumulate_pelt_segments).
 */
static uint32_t pelt_segments(uint64_t periods, uint32_t d1, uint32_t d3)
{
    uint32_t c1, c2;

    c1 = (uint32_t)pelt_decay_load((uint64_t)d1, periods);
    c2 = LOAD_AVG_MAX - (uint32_t)pelt_decay_load(LOAD_AVG_MAX, periods) - 1024;
    return c1 + c2 + d3;
}

/**
 * Decay the sums of `sa` across the periods that `delta` units, added to
 * the part of the period already passed, complete, and add the time since
 * the last update by state (accumulate_sum). Return the periods passed.
 */
static uint64_t pelt_accumulate(uint64_t delta, struct sched_avg *sa, unsigned long load,
                                unsigned long runnable, int running)
{
    uint32_t contrib = (uint32_t)delta, rem;
    uint64_t periods;

    delta += sa->period_contrib;
    periods = delta >> 10;
    if (periods) {
        sa->load_sum = pelt_decay_load(sa->load_sum, periods);
        sa->runnable_sum = pelt_decay_load(sa->runnable_sum, periods);
        sa->util_sum = (uint32_t)pelt_decay_load((uint64_t)sa->util_sum, periods);
        rem = (uint32_t)(delta & 1023u);
        delta = rem;
        /* With no load, runnable and running are 0 too, so the
         * contribution is not used. */
        if (load) {
            contrib = pelt_segments(periods, 1024 - sa->period_contrib, rem);
        }
    }
    sa->period_contrib = (uint32_t)delta;
    if (load) {
        sa->load_sum += (uint64_t)load * contrib;
    }
    if (runnable) {
        sa->runnable_sum += ((uint64_t)runnable * contrib) << SCHED_CAPACITY_SHIFT;
    }
    if (running) {
        sa->util_sum += contrib << SCHED_CAPACITY_SHIFT;
    }
    return periods;
}

int pelt_update_sum(uint64_t now, struct sched_avg *sa, unsigned long load, unsigned long runnable,
                    int running)
{
    uint64_t delta;

    if (now < sa->last_update_time) {
        sa->last_update_time = now;
        return 0;
    }
    delta = (now - sa->last_update_time) >> 10;
    if (!delta) {
        return 0;
    }
    sa->last_update_time += delta << 10;
    /* Running and runnable are subsets of load: an entity off its queue
     * that is still its queue's current counts as neither. */
    if (!load) {
        runnable = 0;
        running = 0;
    }
    return pelt_accumulate(delta, sa, load, runnable, running) != 0;
}

void pelt_update_avg(struct sched_avg *sa, unsigned long load)
{
    uint32_t divider = pelt_divider(sa);

    sa->load_avg = (unsigned long)pelt_div((uint64_t)load * sa->load_sum, divider);
    sa->runnable_avg = (unsigned long)pelt_div(sa->runnable_sum, divider);
    sa->util_avg = sa->util_sum / divider;
}

/** Clear util_est's mark that util_avg has not changed (cfs_se_util_change). */
static void pelt_util_changed(struct sched_avg *sa)
{
    if (sa->util_est & UTIL_AVG_UNCHANGED) {
        sa->util_est &= ~UTIL_AVG_UNCHANGED;
    }
}

int pelt_update_blocked_se(uint64_t now, struct sched_entity *se)
{
    if (pelt_update_sum(now, &se->avg, 0, 0, 0)) {
        pelt_update_avg(&se->avg, se_weight(se));
        return 1;
    }
    return 0;
}

int pelt_update_se(uint64_t now, struct cfs_rq *cfs_rq, struct sched_entity *se)
{
    if (pelt_update_sum(now, &se->avg, !!se->on_rq, se_runnable(se), cfs_rq->curr == se)) {
        pelt_update_avg(&se->avg, se_weight(se));
        pelt_util_changed(&se->avg);
        return 1;
    }
    return 0;
}

int pelt_update_cfs_rq(uint64_t now, struct cfs_rq *cfs_rq)
{
    if (pelt_update_sum(now, &cfs_rq->avg, cfs_rq->load.weight, cfs_rq->h_nr_runnable,
                        cfs_rq->curr != NULL)) {
        pelt_update_avg(&cfs_rq->avg, 1);
        return 1;
    }
    return 0;
}

int pelt_update_rt(int cpu, uint64_t now, int running)
{
    struct sched_avg *sa = &pelt_rt[cpu];

    if (pelt_update_sum(now, sa, (unsigned long)running, (unsigned long)running, running)) {
        pelt_update_avg(sa, 1);
        return 1;
    }
    return 0;
}

int pelt_update_irq(int cpu, uint64_t clock, uint64_t running)
{
    struct sched_avg *sa = &pelt_irq[cpu];
    int ret;

    /* The interrupt time is taken as coming just before `clock`: decay
     * across the time before it as idle, then add it as running. */
    ret = pelt_update_sum(clock - running, sa, 0, 0, 0);
    ret += pelt_update_sum(clock, sa, 1, 1, 1);
    if (ret) {
        pelt_update_avg(sa, 1);
    }
    return ret;
}

unsigned long pelt_cpu_util_rt(int cpu)
{
    return pelt_rt[cpu].util_avg;
}

unsigned long pelt_cpu_util_irq(int cpu)
{
    return pelt_irq[cpu].util_avg;
}

void pelt_init_entity(struct sched_entity *se)
{
    struct sched_avg *sa = &se->avg;

    sa->last_update_time = 0;
    sa->load_sum = 0;
    sa->runnable_sum = 0;
    sa->util_sum = 0;
    sa->period_contrib = 0;
    sa->load_avg = entity_is_task(se) ? se->load.weight : 0;
    sa->runnable_avg = 0;
    sa->util_avg = 0;
    sa->util_est = 0;
}

void pelt_post_init_entity(struct sched_entity *se)
{
    struct cfs_rq *cfs_rq = se->cfs_rq;
    struct sched_avg *sa = &se->avg;
    long cap = ((long)SCHED_CAPACITY_SCALE - (long)cfs_rq->avg.util_avg) / 2;

    if (cap > 0) {
        if (cfs_rq->avg.util_avg != 0) {
            sa->util_avg = (unsigned long)pelt_div((uint64_t)cfs_rq->avg.util_avg * se_weight(se),
                                                   cfs_rq->avg.load_avg + 1);
            if (sa->util_avg > (unsigned long)cap) {
                sa->util_avg = (unsigned long)cap;
            }
        } else {
            sa->util_avg = (unsigned long)cap;
        }
    }
    sa->runnable_avg = sa->util_avg;
}

void pelt_enqueue_load(struct cfs_rq *cfs_rq, struct sched_entity *se)
{
    cfs_rq->avg.load_avg += se->avg.load_avg;
    cfs_rq->avg.load_sum += (uint64_t)se_weight(se) * se->avg.load_sum;
}

void pelt_dequeue_load(struct cfs_rq *cfs_rq, struct sched_entity *se)
{
    pelt_sub_ul(&cfs_rq->avg.load_avg, se->avg.load_avg);
    pelt_sub_u64(&cfs_rq->avg.load_sum, (uint64_t)se_weight(se) * se->avg.load_sum);
    /* Rounding may leave the sum below what the average implies. */
    if (cfs_rq->avg.load_sum < (uint64_t)cfs_rq->avg.load_avg * PELT_MIN_DIVIDER) {
        cfs_rq->avg.load_sum = (uint64_t)cfs_rq->avg.load_avg * PELT_MIN_DIVIDER;
    }
}

/** Raise a sum to the least its average implies at the smallest divider. */
static void pelt_floor_u64(uint64_t *sum, unsigned long avg)
{
    if (*sum < (uint64_t)avg * PELT_MIN_DIVIDER) {
        *sum = (uint64_t)avg * PELT_MIN_DIVIDER;
    }
}

/** As `pelt_floor_u64`, for a 32-bit sum. */
static void pelt_floor_u32(uint32_t *sum, unsigned long avg)
{
    if (*sum < (uint32_t)(avg * PELT_MIN_DIVIDER)) {
        *sum = (uint32_t)(avg * PELT_MIN_DIVIDER);
    }
}

/** Note a change of a group queue's runnable sum, for its group entity to
 * take at its next update (add_tg_cfs_propagate). */
static void pelt_add_propagate(struct cfs_rq *cfs_rq, long runnable_sum)
{
    cfs_rq->propagate = 1;
    cfs_rq->prop_runnable_sum += runnable_sum;
}

int pelt_update_cfs_rq_load(uint64_t now, struct cfs_rq *cfs_rq)
{
    struct sched_avg *sa = &cfs_rq->avg;
    unsigned long removed_load, removed_util, removed_runnable;
    uint32_t divider;
    int decayed = 0;

    if (cfs_rq->removed.nr) {
        divider = pelt_divider(sa);
        removed_load = cfs_rq->removed.load_avg;
        removed_util = cfs_rq->removed.util_avg;
        removed_runnable = cfs_rq->removed.runnable_avg;
        cfs_rq->removed.load_avg = 0;
        cfs_rq->removed.util_avg = 0;
        cfs_rq->removed.runnable_avg = 0;
        cfs_rq->removed.nr = 0;

        pelt_sub_ul(&sa->load_avg, removed_load);
        pelt_sub_u64(&sa->load_sum, (uint64_t)removed_load * divider);
        pelt_floor_u64(&sa->load_sum, sa->load_avg);

        pelt_sub_ul(&sa->util_avg, removed_util);
        pelt_sub_u32(&sa->util_sum, (uint32_t)(removed_util * divider));
        pelt_floor_u32(&sa->util_sum, sa->util_avg);

        pelt_sub_ul(&sa->runnable_avg, removed_runnable);
        pelt_sub_u64(&sa->runnable_sum, (uint64_t)removed_runnable * divider);
        pelt_floor_u64(&sa->runnable_sum, sa->runnable_avg);

        /* The runnable average is the load's, unweighted: its sum
         * estimates the load sum that left. */
        pelt_add_propagate(cfs_rq,
                           -(long)(((uint64_t)removed_runnable * divider) >> SCHED_CAPACITY_SHIFT));
        decayed = 1;
    }
    decayed |= pelt_update_cfs_rq(now, cfs_rq);
    return decayed;
}

void pelt_attach_entity(struct cfs_rq *cfs_rq, struct sched_entity *se)
{
    uint32_t divider = pelt_divider(&cfs_rq->avg);
    unsigned long weight = se_weight(se);

    /* Align the entity's period to the queue's, and rebuild its sums from
     * its averages at that place. */
    se->avg.last_update_time = cfs_rq->avg.last_update_time;
    se->avg.period_contrib = cfs_rq->avg.period_contrib;
    se->avg.util_sum = (uint32_t)(se->avg.util_avg * divider);
    se->avg.runnable_sum = (uint64_t)se->avg.runnable_avg * divider;
    se->avg.load_sum = (uint64_t)se->avg.load_avg * divider;
    if (weight < se->avg.load_sum) {
        se->avg.load_sum = pelt_div(se->avg.load_sum, weight);
    } else {
        se->avg.load_sum = 1;
    }
    pelt_enqueue_load(cfs_rq, se);
    cfs_rq->avg.util_avg += se->avg.util_avg;
    cfs_rq->avg.util_sum += se->avg.util_sum;
    cfs_rq->avg.runnable_avg += se->avg.runnable_avg;
    cfs_rq->avg.runnable_sum += se->avg.runnable_sum;
    pelt_add_propagate(cfs_rq, (long)se->avg.load_sum);
}

void pelt_detach_entity(struct cfs_rq *cfs_rq, struct sched_entity *se)
{
    pelt_dequeue_load(cfs_rq, se);
    pelt_sub_ul(&cfs_rq->avg.util_avg, se->avg.util_avg);
    pelt_sub_u32(&cfs_rq->avg.util_sum, se->avg.util_sum);
    pelt_floor_u32(&cfs_rq->avg.util_sum, cfs_rq->avg.util_avg);
    pelt_sub_ul(&cfs_rq->avg.runnable_avg, se->avg.runnable_avg);
    pelt_sub_u64(&cfs_rq->avg.runnable_sum, se->avg.runnable_sum);
    pelt_floor_u64(&cfs_rq->avg.runnable_sum, cfs_rq->avg.runnable_avg);
    pelt_add_propagate(cfs_rq, -(long)se->avg.load_sum);
}

/**
 * Give a group entity its group queue's utilization, which is the same
 * entity's seen from below, and pass the change to the parent queue
 * (update_tg_cfs_util).
 */
static void pelt_tg_util(struct cfs_rq *cfs_rq, struct sched_entity *se, struct cfs_rq *gcfs_rq)
{
    long delta_avg = (long)gcfs_rq->avg.util_avg - (long)se->avg.util_avg, delta_sum;
    uint32_t new_sum, divider;

    if (!delta_avg) {
        return;
    }
    divider = pelt_divider(&cfs_rq->avg);
    se->avg.util_avg = gcfs_rq->avg.util_avg;
    new_sum = (uint32_t)(se->avg.util_avg * divider);
    delta_sum = (long)new_sum - (long)se->avg.util_sum;
    se->avg.util_sum = new_sum;
    pelt_add_ul(&cfs_rq->avg.util_avg, delta_avg);
    pelt_add_u32(&cfs_rq->avg.util_sum, delta_sum);
    pelt_floor_u32(&cfs_rq->avg.util_sum, cfs_rq->avg.util_avg);
}

/** The same for the runnable average (update_tg_cfs_runnable). */
static void pelt_tg_runnable(struct cfs_rq *cfs_rq, struct sched_entity *se, struct cfs_rq *gcfs_rq)
{
    long delta_avg = (long)gcfs_rq->avg.runnable_avg - (long)se->avg.runnable_avg;
    uint64_t new_sum;
    int64_t delta_sum;
    uint32_t divider;

    if (!delta_avg) {
        return;
    }
    divider = pelt_divider(&cfs_rq->avg);
    se->avg.runnable_avg = gcfs_rq->avg.runnable_avg;
    new_sum = (uint64_t)se->avg.runnable_avg * divider;
    delta_sum = (int64_t)new_sum - (int64_t)se->avg.runnable_sum;
    se->avg.runnable_sum = new_sum;
    pelt_add_ul(&cfs_rq->avg.runnable_avg, delta_avg);
    pelt_add_u64(&cfs_rq->avg.runnable_sum, delta_sum);
    pelt_floor_u64(&cfs_rq->avg.runnable_sum, cfs_rq->avg.runnable_avg);
}

/**
 * Change a group entity's load by the runnable sum that joined or left its
 * group queue (update_tg_cfs_load): an addition is taken as overlapping
 * nothing already runnable, up to the divider; a removal leaves each task
 * equally runnable, the queue's load sum over its weight; and the result is
 * never below the entity's running sum.
 */
static void pelt_tg_load(struct cfs_rq *cfs_rq, struct sched_entity *se, struct cfs_rq *gcfs_rq)
{
    long runnable_sum = gcfs_rq->prop_runnable_sum, running_sum, delta_avg;
    unsigned long load_avg, gweight;
    uint64_t load_sum = 0;
    int64_t delta_sum;
    uint32_t divider;

    if (!runnable_sum) {
        return;
    }
    gcfs_rq->prop_runnable_sum = 0;
    divider = pelt_divider(&cfs_rq->avg);
    if (runnable_sum >= 0) {
        uint64_t sum = (uint64_t)runnable_sum + se->avg.load_sum;

        runnable_sum = (long)(sum < divider ? sum : divider);
    } else {
        gweight = gcfs_rq->load.weight;
        if (gweight) {
            load_sum = pelt_div(gcfs_rq->avg.load_sum, gweight);
        }
        runnable_sum = (long)(se->avg.load_sum < load_sum ? se->avg.load_sum : load_sum);
    }
    running_sum = (long)(se->avg.util_sum >> SCHED_CAPACITY_SHIFT);
    if (runnable_sum < running_sum) {
        runnable_sum = running_sum;
    }
    load_sum = (uint64_t)se_weight(se) * (unsigned long)runnable_sum;
    load_avg = (unsigned long)pelt_div(load_sum, divider);
    delta_avg = (long)load_avg - (long)se->avg.load_avg;
    if (!delta_avg) {
        return;
    }
    delta_sum = (int64_t)load_sum - (int64_t)((uint64_t)se_weight(se) * se->avg.load_sum);
    se->avg.load_sum = (uint64_t)runnable_sum;
    se->avg.load_avg = load_avg;
    pelt_add_ul(&cfs_rq->avg.load_avg, delta_avg);
    pelt_add_u64(&cfs_rq->avg.load_sum, delta_sum);
    pelt_floor_u64(&cfs_rq->avg.load_sum, cfs_rq->avg.load_avg);
}

/** Fold a group queue's pending change into its group entity and pass it
 * up (propagate_entity_load_avg); 1 when there was one. */
static int pelt_propagate(struct sched_entity *se)
{
    struct cfs_rq *cfs_rq, *gcfs_rq;

    if (entity_is_task(se)) {
        return 0;
    }
    gcfs_rq = se->my_q;
    if (!gcfs_rq->propagate) {
        return 0;
    }
    gcfs_rq->propagate = 0;
    cfs_rq = se->cfs_rq;
    pelt_add_propagate(cfs_rq, gcfs_rq->prop_runnable_sum);
    pelt_tg_util(cfs_rq, se, gcfs_rq);
    pelt_tg_runnable(cfs_rq, se, gcfs_rq);
    pelt_tg_load(cfs_rq, se, gcfs_rq);
    return 1;
}

void pelt_update_tg_load(struct cfs_rq *cfs_rq, uint64_t now)
{
    long delta;
    long contrib = (long)cfs_rq->tg_load_avg_contrib;

    if (cfs_rq->tg == &root_task_group) {
        return;
    }
    if (now - cfs_rq->last_update_tg_load_avg < 1000000u) {
        return;
    }
    delta = (long)cfs_rq->avg.load_avg - contrib;
    if ((delta < 0 ? -delta : delta) > contrib / 64) {
        cfs_rq->tg->load_avg += delta;
        cfs_rq->tg_load_avg_contrib = cfs_rq->avg.load_avg;
        cfs_rq->last_update_tg_load_avg = now;
    }
}

void pelt_clear_tg_load(struct cfs_rq *cfs_rq, uint64_t now)
{
    if (cfs_rq->tg == &root_task_group) {
        return;
    }
    cfs_rq->tg->load_avg -= (long)cfs_rq->tg_load_avg_contrib;
    cfs_rq->tg_load_avg_contrib = 0;
    cfs_rq->last_update_tg_load_avg = now;
}

void pelt_update_load_avg(uint64_t now, struct cfs_rq *cfs_rq, struct sched_entity *se, int flags)
{
    int decayed;

    if (se->avg.last_update_time && !(flags & FAIR_LOAD_SKIP_AGE)) {
        pelt_update_se(now, cfs_rq, se);
    }
    decayed = pelt_update_cfs_rq_load(now, cfs_rq);
    decayed |= pelt_propagate(se);
    if (!se->avg.last_update_time && (flags & FAIR_LOAD_ATTACH)) {
        /* An entity that migrated, whose time migration cleared, joins
         * the queue of its new processor. */
        pelt_attach_entity(cfs_rq, se);
        pelt_update_tg_load(cfs_rq, now);
    } else if (flags & FAIR_LOAD_DETACH) {
        pelt_detach_entity(cfs_rq, se);
        pelt_update_tg_load(cfs_rq, now);
    } else if (decayed && (flags & FAIR_LOAD_UPDATE_TG)) {
        pelt_update_tg_load(cfs_rq, now);
    }
}

void pelt_sync_entity(struct sched_entity *se)
{
    pelt_update_blocked_se(se->cfs_rq->avg.last_update_time, se);
}

void pelt_remove_entity(struct sched_entity *se)
{
    struct cfs_rq *cfs_rq = se->cfs_rq;

    pelt_sync_entity(se);
    cfs_rq->removed.nr++;
    cfs_rq->removed.util_avg += se->avg.util_avg;
    cfs_rq->removed.load_avg += se->avg.load_avg;
    cfs_rq->removed.runnable_avg += se->avg.runnable_avg;
}

/** Whether every sum of `sa` has decayed to 0 (load_avg_is_decayed). */
static int pelt_avg_decayed(const struct sched_avg *sa)
{
    return !sa->load_sum && !sa->util_sum && !sa->runnable_sum;
}

void pelt_migrate_lag(struct sched_entity *se)
{
    struct fair_rq *rq = &fair_rqs[se->cfs_rq->cpu];

    if (pelt_avg_decayed(&se->avg) || rq->curr) {
        return;
    }
    /* With no fair thread running there the queue's averages may be
     * stale; the source's task clock, which the caller has updated, is
     * now (migrate_se_pelt_lag's estimate). */
    if (rq->clock_task > se->cfs_rq->avg.last_update_time) {
        pelt_update_blocked_se(rq->clock_task, se);
    }
}

/** A task entity's utilization estimate without its unchanged mark. */
static unsigned long pelt_util_est_of(const struct sched_entity *se)
{
    return se->avg.util_est & ~UTIL_AVG_UNCHANGED;
}

unsigned long pelt_task_util_est(const struct sched_entity *se)
{
    unsigned long est = pelt_util_est_of(se);

    return se->avg.util_avg > est ? se->avg.util_avg : est;
}

void pelt_util_est_enqueue(struct cfs_rq *cfs_rq, struct sched_entity *se)
{
    cfs_rq->avg.util_est += (unsigned int)pelt_util_est_of(se);
}

void pelt_util_est_dequeue(struct cfs_rq *cfs_rq, struct sched_entity *se)
{
    unsigned int est = (unsigned int)pelt_util_est_of(se);

    cfs_rq->avg.util_est -= est < cfs_rq->avg.util_est ? est : cfs_rq->avg.util_est;
}

void pelt_util_est_update(struct cfs_rq *cfs_rq, struct sched_entity *se, int sleep)
{
    unsigned int ewma, dequeued, diff;

    (void)cfs_rq;
    if (!sleep) {
        return;
    }
    ewma = se->avg.util_est;
    if (ewma & UTIL_AVG_UNCHANGED) {
        return;
    }
    dequeued = (unsigned int)se->avg.util_avg;
    if (ewma <= dequeued) {
        ewma = dequeued;
        goto done;
    }
    diff = ewma - dequeued;
    if (diff < UTIL_EST_MARGIN) {
        goto done;
    }
    /* A task above the processor's capacity is not estimated. */
    if (dequeued > SCHED_CAPACITY_SCALE) {
        return;
    }
    /* A task that waited for the processor ran less than it would have:
     * keep the estimate. */
    if ((unsigned long)(dequeued + UTIL_EST_MARGIN) < se->avg.runnable_avg) {
        goto done;
    }
    /* ewma = ewma - (ewma - dequeued) / 4, in fixed point. */
    ewma <<= UTIL_EST_WEIGHT_SHIFT;
    ewma -= diff;
    ewma >>= UTIL_EST_WEIGHT_SHIFT;
done:
    se->avg.util_est = ewma | UTIL_AVG_UNCHANGED;
}

int pelt_cfs_rq_has_blocked(const struct cfs_rq *cfs_rq)
{
    return cfs_rq->avg.load_avg || cfs_rq->avg.util_avg;
}

int pelt_cfs_rq_decayed(const struct cfs_rq *cfs_rq)
{
    if (cfs_rq->load.weight) {
        return 0;
    }
    if (!pelt_avg_decayed(&cfs_rq->avg)) {
        return 0;
    }
    /* A child on the leaf list comes just before its parent
     * (child_cfs_rq_on_list). */
    if (cfs_rq->on_list && cfs_rq->leaf_prev && cfs_rq->leaf_prev->tg->parent == cfs_rq->tg) {
        return 0;
    }
    return cfs_rq->tg_load_avg_contrib == 0;
}

/** Whether a sleeping group entity has nothing to decay and nothing to take
 * from below (skip_blocked_update). */
static int pelt_skip_blocked(const struct sched_entity *se)
{
    if (se->avg.load_avg || se->avg.util_avg) {
        return 0;
    }
    return !se->my_q->propagate;
}

int pelt_update_blocked(int cpu, uint64_t now, int rt_running)
{
    struct cfs_rq *cfs_rq, *next;
    struct sched_entity *se;
    int blocked = 0;

    pelt_update_rt(cpu, now, rt_running);
    if (pelt_rt[cpu].util_avg || pelt_irq[cpu].util_avg) {
        blocked = 1;
    }
    /* Children come before their parents on the leaf list, so a change
     * reaches the root in one walk (for_each_leaf_cfs_rq_safe). */
    for (cfs_rq = fair_rqs[cpu].leaf_head; cfs_rq; cfs_rq = next) {
        next = cfs_rq->leaf_next;
        if (pelt_update_cfs_rq_load(now, cfs_rq)) {
            pelt_update_tg_load(cfs_rq, now);
        }
        se = cfs_rq_group_se(cfs_rq);
        if (se && !pelt_skip_blocked(se)) {
            pelt_update_load_avg(now, se->cfs_rq, se, FAIR_LOAD_UPDATE_TG);
        }
        if (pelt_cfs_rq_decayed(cfs_rq)) {
            fair_leaf_del(cfs_rq);
        }
        if (pelt_cfs_rq_has_blocked(cfs_rq)) {
            blocked = 1;
        }
    }
    return blocked;
}

/**
 * Compute the hierarchical load of `cfs_rq` and the queues above it, once
 * per tick: each queue's share of the root's load is its parent's times its
 * group entity's part of the parent's load (update_cfs_rq_h_load).
 */
static void pelt_h_load(struct cfs_rq *cfs_rq, uint64_t tick)
{
    struct sched_entity *se = cfs_rq_group_se(cfs_rq);
    unsigned long load;

    if (cfs_rq->last_h_load_update == tick) {
        return;
    }
    cfs_rq->h_load_next = NULL;
    for (; se; se = se->parent) {
        cfs_rq = se->cfs_rq;
        cfs_rq->h_load_next = se;
        if (cfs_rq->last_h_load_update == tick) {
            break;
        }
    }
    if (!se) {
        cfs_rq->h_load = cfs_rq->avg.load_avg;
        cfs_rq->last_h_load_update = tick;
    }
    while ((se = cfs_rq->h_load_next) != NULL) {
        load = cfs_rq->h_load;
        load = (unsigned long)pelt_div((uint64_t)load * se->avg.load_avg,
                                       (uint64_t)cfs_rq->avg.load_avg + 1);
        cfs_rq = se->my_q;
        cfs_rq->h_load = load;
        cfs_rq->last_h_load_update = tick;
    }
}

unsigned long pelt_task_h_load(struct sched_entity *se, uint64_t tick)
{
    struct cfs_rq *cfs_rq = se->cfs_rq;

    pelt_h_load(cfs_rq, tick);
    return (unsigned long)pelt_div((uint64_t)se->avg.load_avg * cfs_rq->h_load,
                                   (uint64_t)cfs_rq->avg.load_avg + 1);
}

/**
 * Give `se` on `cfs_rq` its load average for the weight it has now, its load
 * having been `old_weight`'s: out of the queue's sums at the old weight, back
 * at the new (reweight_entity's dequeue_load_avg and enqueue_load_avg).
 */
static void pelt_reweight(struct cfs_rq *cfs_rq, struct sched_entity *se, unsigned long old_weight)
{
    uint32_t divider = pelt_divider(&se->avg);

    pelt_sub_ul(&cfs_rq->avg.load_avg, se->avg.load_avg);
    pelt_sub_u64(&cfs_rq->avg.load_sum, (uint64_t)old_weight * se->avg.load_sum);
    pelt_floor_u64(&cfs_rq->avg.load_sum, cfs_rq->avg.load_avg);
    se->avg.load_avg = (unsigned long)pelt_div((uint64_t)se_weight(se) * se->avg.load_sum, divider);
    pelt_enqueue_load(cfs_rq, se);
}

/** `fair_hooks.load_update`: update_load_avg at the processor's task clock,
 * then se_update_runnable, a group entity's runnable count from its queue. */
static void pelt_hook_update(struct cfs_rq *cfs_rq, struct sched_entity *se, int flags)
{
    pelt_update_load_avg(fair_rqs[cfs_rq->cpu].clock_task, cfs_rq, se, flags);
    if (!entity_is_task(se)) {
        se->runnable_weight = se->my_q->h_nr_runnable;
    }
}

/** `fair_hooks.load_remove`: an entity leaving its queue by migration or
 * death (migrate_task_rq_fair's remove_entity_load_avg and
 * migrate_se_pelt_lag, and task_dead_fair's). */
static void pelt_hook_remove(struct sched_entity *se)
{
    pelt_remove_entity(se);
    pelt_migrate_lag(se);
}

/** `fair_hooks.load_init`: a new entity's averages, a thread's pointing at
 * its queue on the processor it starts on; a group's new entity starts
 * empty (init_entity_runnable_average, and post_init_entity_util_avg for a
 * thread). */
static void pelt_hook_init(struct sched_entity *se)
{
    pelt_init_entity(se);
    if (entity_is_task(se)) {
        pelt_post_init_entity(se);
    }
}

void pelt_init(void)
{
    fair_hooks.load_update = pelt_hook_update;
    fair_hooks.load_reweight = pelt_reweight;
    fair_hooks.load_remove = pelt_hook_remove;
    fair_hooks.load_init = pelt_hook_init;
}
